#!/usr/bin/env node
// bin/open-update-pr.mjs — 自动开 PR 并合并（detect-and-pr job 的编排逻辑）
// 由 .github/workflows/auto-update.yml 调用，接收 GITHUB_TOKEN 环境变量
// 职责：git 配置 → 创建分支 → 暂存提交 → 推送 → 开 PR → 合并 → 清理远程分支

import { execSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';

// ─── 环境 ────────────────────────────────────────────────────────────────

const GITHUB_REPOSITORY = process.env.GITHUB_REPOSITORY || '';
const GITHUB_ACTOR = process.env.GITHUB_ACTOR || 'github-actions[bot]';
const GITHUB_TOKEN = process.env.GITHUB_TOKEN;
const PAT_TOKEN = process.env.PAT_TOKEN || GITHUB_TOKEN;

if (!PAT_TOKEN) {
  console.error('[ERROR] 缺少 GITHUB_TOKEN / PAT_TOKEN 环境变量');
  process.exit(1);
}

// ─── Git 配置 ────────────────────────────────────────────────────────────

execSync('git config user.name "github-actions[bot]"', { stdio: 'inherit' });
execSync('git config user.email "github-actions[bot]@users.noreply.github.com"', { stdio: 'inherit' });

// ─── 分支名 ──────────────────────────────────────────────────────────────

const today = new Date().toISOString().slice(0, 10);
const branch = `auto-update/${today}`;

// ─── 检查是否已有今日 open PR ──────────────────────────────────────────

try {
  const listResult = execSync(
    `curl -s -H "Authorization: token ${PAT_TOKEN}" \
       "https://api.github.com/repos/${GITHUB_REPOSITORY}/pulls?state=open&head=${GITHUB_REPOSITORY.split('/')[0]}:${branch}"`,
    { encoding: 'utf8' }
  );
  const existingPRs = JSON.parse(listResult);
  if (existingPRs.length > 0) {
    console.log(`[SKIP] 今日 (${today}) 已存在 PR #${existingPRs[0].number}，跳过`);
    process.exit(0);
  }
} catch (_) {
  // 网络错误时继续尝试
}

// ─── 检查是否有变更文件 ─────────────────────────────────────────────────

execSync('git add -A');
const status = execSync('git status --porcelain').toString();
if (!status.trim()) {
  console.log('[SKIP] 无文件改动，跳过');
  process.exit(0);
}

// ─── 提交 ───────────────────────────────────────────────────────────────

execSync(
  `git commit -m "chore(deps): auto-update ${today}\n\n[skip ci]" ` +
  `-m "本批次自动检测到的更新（含 README 同步）。\\n\\n🤖 Generated by .github/workflows/auto-update.yml"`,
  { stdio: 'inherit' }
);

// ─── 推送分支 ───────────────────────────────────────────────────────────

execSync(`git push --force origin ${branch}`, { stdio: 'inherit' });
console.log(`[OK] 推送分支 ${branch}`);

// ─── 读取 updates.json 生成 PR body ────────────────────────────────────

let body = '';
if (existsSync('updates.json')) {
  try {
    const updates = JSON.parse(readFileSync('updates.json', 'utf8')).updates;
    body = `## 自动检测到的新版本\n\n检测时间：\`${new Date().toISOString()}\`\n\n`;
    for (const u of updates) {
      body += `### ${u.app}\n\n`;
      body += `| service | image | before | after |\n`;
      body += `|---------|-------|--------|-------|\n`;
      for (const svc of u.services) {
        body += `| ${svc.name} | ${svc.repo} | \`${svc.from}\` | \`${svc.to}\` |\n`;
      }
      body += '\n';
    }
    body += '## 修改文件\n\n';
    const changedFiles = execSync('git diff --name-only HEAD~1').toString().trim().split('\n');
    for (const f of changedFiles) {
      if (f) body += `- \`${f}\`\n`;
    }
  } catch (_) {
    body = `自动更新 ${today}`;
  }
} else {
  body = `自动更新 ${today}`;
}
body += `\n\n---\n🤖 由 \`.github/workflows/auto-update.yml\` 自动生成并自动合并。\n`;

// ─── 开 PR ──────────────────────────────────────────────────────────────

const prTitle = `chore(deps): auto-update ${today} [skip ci]`;
const createPRCmd =
  `curl -s -X POST \
   -H "Authorization: token ${PAT_TOKEN}" \
   -H "Content-Type: application/json" \
   -d ${JSON.stringify(JSON.stringify({
    title: prTitle,
    head: branch,
    base: 'main',
    body,
  }))} \
   "https://api.github.com/repos/${GITHUB_REPOSITORY}/pulls"`;

let prData;
try {
  const prRaw = execSync(createPRCmd, { encoding: 'utf8' });
  prData = JSON.parse(prRaw);
  console.log(`[OK] PR 已开: ${prData.html_url}`);
} catch (e) {
  console.error('[ERROR] 创建 PR 失败:', e.message);
  process.exit(1);
}

// ─── 合并 PR ────────────────────────────────────────────────────────────

const prNumber = prData.number;
const mergeCmd =
  `curl -s -X PUT \
   -H "Authorization: token ${PAT_TOKEN}" \
   -H "Content-Type: application/json" \
   -d ${JSON.stringify(JSON.stringify({ merge_method: 'merge' }))} \
   "https://api.github.com/repos/${GITHUB_REPOSITORY}/pulls/${prNumber}/merge"`;

try {
  const mergeResult = execSync(mergeCmd, { encoding: 'utf8' });
  const mergeData = JSON.parse(mergeResult);
  if (mergeData.merged) {
    console.log(`[OK] PR #${prNumber} 已合并到 main`);
  } else {
    console.warn(`[WARN] PR #${prNumber} 合并状态: ${mergeData.message}`);
  }
} catch (e) {
  console.error(`[ERROR] 合并 PR #${prNumber} 失败:`, e.message);
  // 非致命，继续清理
}

// ─── 清理远程分支 ───────────────────────────────────────────────────────

const deleteBranchCmd =
  `curl -s -X DELETE \
   -H "Authorization: token ${PAT_TOKEN}" \
   "https://api.github.com/repos/${GITHUB_REPOSITORY}/git/refs/heads/${branch}"`;

try {
  execSync(deleteBranchCmd);
  console.log(`[OK] 远程分支 ${branch} 已删除`);
} catch (e) {
  console.warn(`[WARN] 删除远程分支失败（非致命）: ${e.message}`);
}

console.log('[DONE] open-update-pr 完成');
